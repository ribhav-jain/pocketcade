// tools/gen-registry: scans packages/games/* and writes, under apps/web/src/games/, registry.generated.ts (a lazy
// loader per game), metas.generated.ts (each GameMeta), listings.generated.ts (title, tagline, category, tags,
// accent and blurb from each game.md) and details.generated.ts (controls, FAQ and cover alt text), then copies each
// game's media/cover.svg to apps/web/public/covers/.
// Runs as the @pocketcade/web#catalog task. `--check` validates the game folders without writing.
// Usage: node tools/gen-registry.ts [--check]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

interface GameEntry {
  id: string;
  pkg: string;
}

function listGames(rootDir: string): GameEntry[] {
  const dir = join(rootDir, 'packages', 'games');
  return readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'package.json')))
    .map((d) => {
      const pkg = JSON.parse(readFileSync(join(dir, d.name, 'package.json'), 'utf8')) as {
        name: string;
      };
      if (pkg.name !== `@pocketcade/game-${d.name}`)
        throw new Error(
          `${d.name}: package name must be @pocketcade/game-${d.name}, got ${pkg.name}`,
        );
      return { id: d.name, pkg: pkg.name };
    })
    .sort((a, b) => (a.id < b.id ? -1 : 1));
}

const header = (source: string) =>
  `// GENERATED by tools/gen-registry — do not edit. Source: packages/games/*/${source}`;

/** registry.generated.ts: one lazy chunk per game (only GameHost loads these). */
export function renderRegistry(games: GameEntry[]): string {
  return [
    header('package.json'),
    "import type { GameDefinition } from '@pocketcade/sdk';",
    '',
    'export const gameLoaders = {',
    ...games.map((g) => `  '${g.id}': () => import('${g.pkg}'),`),
    '} satisfies Record<string, () => Promise<{ default: GameDefinition }>>;',
    '',
    'export type GameId = keyof typeof gameLoaders;',
    '',
  ].join('\n');
}

/** metas.generated.ts: each game's GameMeta, read by the catalog (kept apart so the player doesn't bundle them). */
export function renderMetas(games: GameEntry[]): string {
  return [
    header('src/meta.ts'),
    "import type { GameMeta } from '@pocketcade/sdk';",
    "import type { GameId } from './registry.generated';",
    ...games.map((g, i) => `import { meta as m${i} } from '${g.pkg}/meta';`),
    '',
    'export const gameMetas: Record<GameId, GameMeta> = {',
    ...games.map((g, i) => `  '${g.id}': m${i},`),
    '};',
    '',
  ].join('\n');
}

/** A game's portal listing, from its game.md: front matter plus the body text as the blurb. */
export interface GameListing {
  title: string;
  /** one line for cards, search and the page description */
  tagline: string;
  category: string;
  tags: string[];
  /** '#RRGGBB': card glow and page tint */
  accent: string;
  /** typical session length */
  minutes: number;
  /** a short paragraph for the game page and the hero */
  blurb: string;
}

/** What a game page shows beyond the listing. */
export interface GameDetails {
  controls: Array<{ action: string; keyboard?: string; pointer?: string; touch?: string }>;
  faq: Array<{ q: string; a: string }>;
  /** describes the cover art: alt text and og:image:alt */
  alt: string;
}

const isText = (v: unknown): v is string => typeof v === 'string' && v.trim() !== '';
const isObject = (v: unknown): v is Record<string, unknown> =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

/** Parses a game.md: YAML front matter, then the blurb. Throws with the game id on anything missing. */
export function parseGameMd(
  id: string,
  markdown: string,
): { listing: GameListing; details: GameDetails } {
  const match = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`${id}: game.md has no front matter`);
  let m: unknown;
  try {
    m = parse(match[1]!);
  } catch (e) {
    throw new Error(`${id}: game.md front matter is not valid YAML: ${(e as Error).message}`);
  }
  if (!isObject(m)) throw new Error(`${id}: game.md front matter is not a mapping`);
  const need = (ok: boolean, what: string) => {
    if (!ok) throw new Error(`${id}: game.md needs ${what}`);
  };
  for (const key of ['title', 'tagline', 'category', 'coverAlt']) need(isText(m[key]), key);
  need(Array.isArray(m.tags) && m.tags.every(isText), 'tags: [tag, ...]');
  need(isText(m.accent) && /^#[0-9a-f]{6}$/i.test(m.accent), "accent: '#RRGGBB'");
  need(typeof m.minutes === 'number' && m.minutes > 0, 'minutes');
  const controls = m.controls;
  need(
    Array.isArray(controls) &&
      controls.length > 0 &&
      controls.every(
        (c) =>
          isObject(c) &&
          isText(c.action) &&
          ['keyboard', 'pointer', 'touch'].every((k) => c[k] === undefined || isText(c[k])),
      ),
    'controls: [{ action, keyboard?, pointer?, touch? }]',
  );
  const faq = m.faq ?? [];
  need(
    Array.isArray(faq) && faq.every((f) => isObject(f) && isText(f.q) && isText(f.a)),
    'faq: [{ q, a }]',
  );
  const blurb = match[2]!.trim().replace(/\s+/g, ' ');
  need(blurb.length > 0, 'a blurb after the front matter');
  return {
    listing: {
      title: m.title,
      tagline: m.tagline,
      category: m.category,
      tags: m.tags,
      accent: m.accent,
      minutes: m.minutes,
      blurb,
    } as GameListing,
    details: { controls, faq, alt: m.coverAlt } as GameDetails,
  };
}

const gameMdOf = (rootDir: string, id: string) =>
  parseGameMd(id, readFileSync(join(rootDir, 'packages', 'games', id, 'game.md'), 'utf8'));

const entries = (items: Record<string, unknown>) =>
  Object.entries(items).map(([id, v]) => `  '${id}': ${JSON.stringify(v)},`);

/** listings.generated.ts: each game's portal listing (typed by the catalog, so an unknown category or tag fails). */
export function renderListings(listings: Record<string, GameListing>): string {
  return [
    header('game.md'),
    "import type { Listing } from './catalog';",
    "import type { GameId } from './registry.generated';",
    '',
    'export const gameListings: Record<GameId, Listing> = {',
    ...entries(listings),
    '};',
    '',
  ].join('\n');
}

/** details.generated.ts: what each game page shows from game.md (server-only; no client bundle reads it). */
export function renderDetails(details: Record<string, GameDetails>): string {
  return [
    header('game.md'),
    "import type { GameId } from './registry.generated';",
    '',
    'export interface GameDetails {',
    '  controls: ReadonlyArray<{ action: string; keyboard?: string; pointer?: string; touch?: string }>;',
    '  faq: ReadonlyArray<{ q: string; a: string }>;',
    '  alt: string;',
    '}',
    '',
    'export const gameDetails: Record<GameId, GameDetails> = {',
    ...entries(details),
    '};',
    '',
  ].join('\n');
}

const ogOf = (rootDir: string, id: string) =>
  join(rootDir, 'apps', 'web', 'public', 'og', `${id}.jpg`);

const coverOf = (rootDir: string, id: string) =>
  join(rootDir, 'packages', 'games', id, 'media', 'cover.svg');

/** Every game folder registers cleanly, ships a cover and is a `workspace:*` dependency of apps/web. */
export function checkRegistry(rootDir = root): string[] {
  let games: GameEntry[];
  try {
    games = listGames(rootDir);
  } catch (e) {
    return [(e as Error).message];
  }
  if (games.length === 0) return ['no game packages found under packages/games/'];
  const web = JSON.parse(readFileSync(join(rootDir, 'apps', 'web', 'package.json'), 'utf8')) as {
    dependencies?: Record<string, string>;
  };
  const problems: string[] = [];
  for (const g of games) {
    if (web.dependencies?.[g.pkg] !== 'workspace:*')
      problems.push(
        `${g.pkg} must be a "workspace:*" dependency of apps/web (the registry imports it)`,
      );
    if (!existsSync(coverOf(rootDir, g.id))) problems.push(`${g.id}: missing media/cover.svg`);
    if (!existsSync(ogOf(rootDir, g.id)))
      problems.push(`${g.id}: missing apps/web/public/og/${g.id}.jpg (run pnpm og)`);
    try {
      gameMdOf(rootDir, g.id);
    } catch (e) {
      problems.push((e as Error).message);
    }
  }
  return problems;
}

/** Writes `file` only when its content changes, so watchers and caches stay quiet. */
function writeIfChanged(file: string, text: string): void {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== text) writeFileSync(file, text);
}

function generate(rootDir = root): void {
  const games = listGames(rootDir);
  const problems = checkRegistry(rootDir);
  if (problems.length > 0) throw new Error(problems.join('\n'));
  const src = join(rootDir, 'apps', 'web', 'src', 'games');
  const parsed = games.map((g) => [g.id, gameMdOf(rootDir, g.id)] as const);
  writeIfChanged(join(src, 'registry.generated.ts'), renderRegistry(games));
  writeIfChanged(join(src, 'metas.generated.ts'), renderMetas(games));
  writeIfChanged(
    join(src, 'listings.generated.ts'),
    renderListings(Object.fromEntries(parsed.map(([id, p]) => [id, p.listing]))),
  );
  writeIfChanged(
    join(src, 'details.generated.ts'),
    renderDetails(Object.fromEntries(parsed.map(([id, p]) => [id, p.details]))),
  );
  const covers = join(rootDir, 'apps', 'web', 'public', 'covers');
  mkdirSync(covers, { recursive: true });
  for (const g of games)
    writeIfChanged(join(covers, `${g.id}.svg`), readFileSync(coverOf(rootDir, g.id), 'utf8'));
  console.log(
    `gen-registry: ${games.length} game(s) → src/games/*.generated.ts and public/covers/`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const problems = checkRegistry();
    for (const p of problems) console.error(`✗ ${p}`);
    if (problems.length > 0) process.exit(1);
    console.log('gen-registry --check: OK');
  } else {
    generate();
  }
}
